#!/usr/bin/env node
// فاحص جاهزية الدمج: يجيب «هل PR معيّن جاهز للدمج وفق قواعد المستودع؟».
// يقرأ GitHub API فقط (لا يعدّل شيئًا)، ويطبع كل شرط مع دليله بالعربية، ومع --json يطبع
// {pr, ready, checks:[{id, status, evidence}]}. الخروج: 0 جاهز، 1 غير جاهز، 2 خطأ استعمال أو اتصال.
// المستودع من --repo owner/name أو متغير البيئة PR_GATE_REPO، والرمز من GITHUB_TOKEN
// (يعمل بلا رمز على المستودعات العامة ضمن حدود المعدل). لا تبعيات خارجية.

// أسماء نماذج الذكاء الاصطناعي المحظورة في العنوان والمتن ورسائل الالتزامات (قواعد المستودع).
const MODEL_RE = /\b(?:claude|gpt-?\d\w*|gemini|copilot|codex|llama|qwen|mistral|deepseek|openai|kimi)\b/i;
// سطرا الإسناد الآليان المعفيان صراحة، وسطر «Generated by/with» المرافق لهما.
const ATTRIBUTION_RE = /^\s*_?Generated (?:by|with)\b|^\s*(?:Co-Authored-By|Claude-Session)\b/i;
// مرادفات الأدوات الإنجليزية/المختصرة إلى اسم الدور العربي في جدول الملكية.
const ROLE_AR = {
  "جودة": ["الجودة"], quality: ["الجودة"],
  "أمن": ["الأمن"], security: ["الأمن"],
  "خادم": ["الخادم"], server: ["الخادم"], api: ["الخادم"],
  web: ["الويب"], "ويب": ["الويب"],
  ios: ["iOS"], android: ["أندرويد"], "أندرويد": ["أندرويد"],
  media: ["الوسائط"], "وسائط": ["الوسائط"],
  ai: ["الذكاء الاصطناعي"], "ذكاء": ["الذكاء الاصطناعي"],
  infra: ["الرفع والبنية", "البنية"], "بنية": ["البنية"],
  contracts: ["العقود"], "عقود": ["العقود"],
  "منسق": ["المنسّق"], coordinator: ["المنسّق"],
};
// وكلاء الجودة والأمن معفون من شرط سطر المالك (قرار المنسّق).
const EXEMPT_ROLES = new Set(["جودة", "quality", "أمن", "security"]);

/** يقرأ جدول «المسار | … | المالك» من README.md إلى [{prefix, owner}] مرتبة بأطول بادئة أولًا. */
export function parseOwners(readmeText) {
  const owners = [];
  let inTable = false;
  for (const line of readmeText.split("\n")) {
    if (line.includes("| المسار |")) { inTable = true; continue; }
    if (inTable) {
      if (!line.startsWith("|")) break;
      const cells = line.split("|").map((c) => c.trim());
      const m = cells[1]?.match(/^`([^`]+)`$/);
      if (m && cells[3]) owners.push({ prefix: m[1], owner: cells[3] });
    }
  }
  return owners.sort((a, b) => b.prefix.length - a.prefix.length);
}

/** حزمة الملف بأطول بادئة مطابقة، أو null. */
export function packageOf(file, owners) {
  const hit = owners.find((o) => file === o.prefix.replace(/\/$/, "") || file.startsWith(o.prefix));
  return hit ?? null;
}

/** هل يلزم سطر «مراجعة المالك: لا مانع»؟ يُعفى docs/** وطلبات الجودة والأمن. */
export function ownerReviewRequired(role, files, owners) {
  if (EXEMPT_ROLES.has(role)) return { required: false, packages: [] };
  const synonyms = ROLE_AR[role] ?? [];
  const needing = new Set();
  for (const f of files) {
    if (f.startsWith("docs/")) continue;
    const pkg = packageOf(f, owners);
    if (!pkg) continue;
    if (synonyms.some((s) => pkg.owner.includes(s))) continue;
    needing.add(`${pkg.prefix} ← ${pkg.owner}`);
  }
  return { required: needing.size > 0, packages: [...needing] };
}

/** يقيّم تعليق حكم: pass «لا مانع»، pending «لا مانع بشرط» مع الشرط، fail أي مانع آخر. */
export function verdictOf(body) {
  const withoutNegated = body.replace(/لا مانع بشرط/g, "§COND§").replace(/لا مانع/g, "");
  if (body.includes("لا مانع بشرط")) {
    const after = body.split("بشرط")[1] ?? "";
    const condition = after.split("\n")[0].replace(/^[:：،]?\s*/, "").trim();
    return { status: "pending", condition: condition || "(الشرط في متن التعليق)" };
  }
  if (/مانع/.test(withoutNegated)) return { status: "fail" };
  if (body.includes("لا مانع")) return { status: "pass" };
  return { status: "pending", condition: "حكم بلا صيغة معروفة" };
}

/** آخر تعليق يبدأ بأحد البوادئ (الأحدث أولًا). */
function lastVerdict(comments, prefixes) {
  const sorted = [...comments].sort((a, b) => (a.created_at < b.created_at ? 1 : -1));
  return sorted.find((c) => prefixes.some((p) => c.body.trimStart().startsWith(p)));
}

/** تاريخ آخر التزام غير دمجي في الـPR (أقصى committer.date لالتزام بأب واحد). */
export function lastNonMergeCommitDate(commits) {
  const dates = commits.filter((c) => (c.parents ?? []).length <= 1)
    .map((c) => c.commit?.committer?.date).filter(Boolean).sort();
  return dates.at(-1) ?? null;
}

/** ينقي نصًا من سطور الإسناد الآلي واسم ملف القواعد القديم قبل فحص أسماء النماذج. */
function modelNameHit(text) {
  const cleaned = String(text ?? "").split("\n")
    .filter((l) => !ATTRIBUTION_RE.test(l))
    .join("\n")
    .replace(/CLAUDE\.md/g, "RULES.md");
  const m = cleaned.match(MODEL_RE);
  return m ? m[0] : null;
}

/** الفحص الكامل. fetcher: دالة (path) => Promise<JSON>؛ تحقنها الاختبارات من ملفات ثابتة. */
export async function gate(prNumber, { fetcher }) {
  const checks = [];
  const add = (id, status, evidence) => checks.push({ id, status, evidence });

  const pr = await fetcher(`pulls/${prNumber}`);
  const [checksPage, comments, commits, files, readmeRes, openPrs] = await Promise.all([
    fetcher(`commits/${pr.head.sha}/check-runs`),
    fetcher(`issues/${prNumber}/comments`),
    fetcher(`pulls/${prNumber}/commits`),
    fetcher(`pulls/${prNumber}/files`),
    fetcher("contents/README.md"),
    fetcher("pulls?state=open&per_page=100"),
  ]);
  const fileNames = files.map((f) => f.filename);
  const readmeText = Buffer.from(readmeRes.content, "base64").toString("utf8");
  const owners = parseOwners(readmeText);
  const lastCommit = lastNonMergeCommitDate(commits);

  // 1) القاعدة main، وليس مسودة، وقابل للدمج.
  const baseOk = pr.base.ref === "main";
  const draftOk = !pr.draft;
  const mergeOk = pr.mergeable !== false;
  add("base", baseOk && draftOk && mergeOk ? "pass" : "fail",
    `القاعدة ${pr.base.ref}؛ مسودة: ${pr.draft ? "نعم" : "لا"}؛ تعارض: ${pr.mergeable === false ? "نعم" : "لا"}`);

  // 2) CI: كل check-runs على الرأس مكتملة وناجحة (ما يبدأ بـ .github يُستثنى).
  const runs = (checksPage.check_runs ?? []).filter((r) => !r.name.startsWith(".github"));
  // skipped وneutral نجاح: مرشحات المسارات تتخطى وظائف لا تمسها التغييرات (كما في بوابة المنسّق).
  const PASS = new Set(["success", "skipped", "neutral"]);
  const bad = runs.filter((r) => r.status !== "completed" || !PASS.has(r.conclusion));
  add("ci", runs.length && bad.length === 0 ? "pass" : bad.length === 0 ? "pending" : "fail",
    runs.length === 0 ? "لا check-runs على الرأس"
      : bad.length === 0 ? `${runs.length} فحصًا مكتملًا ناجحًا على ${pr.head.sha.slice(0, 7)}`
      : `غير ناجحة: ${bad.map((r) => `${r.name} (${r.status}/${r.conclusion ?? "…"})`).join("، ")}`);

  // 3) حكما الجودة والأمن: بعد آخر التزام غير دمجي، وبلا مانع؛ «لا مانع بشرط» = pending.
  for (const [id, label, prefixes] of [
    ["quality", "الجودة", ["مراجعة الجودة", "QA review"]],
    ["security", "الأمن", ["مراجعة الأمن", "Security review"]],
  ]) {
    const v = lastVerdict(comments, prefixes);
    if (!v) { add(id, "pending", `لا حكم ${label} بعد`); continue; }
    const verdict = verdictOf(v.body);
    const fresh = lastCommit && v.created_at > lastCommit;
    if (!fresh) add(id, "pending", `حكم ${label} (${v.created_at}) أقدم من آخر التزام غير دمجي (${lastCommit})`);
    else if (verdict.status === "pending") add(id, "pending", `حكم ${label}: لا مانع بشرط — ${verdict.condition}`);
    else if (verdict.status === "fail") add(id, "fail", `حكم ${label} فيه مانع (${v.created_at})`);
    else add(id, "pass", `حكم ${label} «لا مانع» في ${v.created_at} بعد آخر التزام`);
  }

  // 4) سطر «مراجعة المالك: لا مانع» حين تمس الملفات حزمة لها مالك غير صاحب الـPR.
  const role = pr.head.ref.match(/^agent\/([^/]+)\//)?.[1] ?? "";
  const ownerRule = ownerReviewRequired(role, fileNames, owners);
  if (!ownerRule.required) add("owner", "pass", "الحزم الممسوكة بملكية صاحب الـPR أو معفاة (docs/**)");
  else {
    const line = comments.find((c) => c.body.includes("مراجعة المالك: لا مانع"));
    add("owner", line ? "pass" : "fail",
      line ? `سطر المالك موجود (${line.created_at})` : `يلزم سطر «مراجعة المالك: لا مانع» — الحزم: ${ownerRule.packages.join("؛ ")}`);
  }

  // 5) التكديس: ملفات الـPR مجموعة شاملة لملفات PR مفتوح آخر.
  const mine = new Set(fileNames);
  let stackedOn = null;
  for (const other of (openPrs ?? [])) {
    if (other.number === prNumber) continue;
    const otherFiles = (await fetcher(`pulls/${other.number}/files`)).map((f) => f.filename);
    if (otherFiles.length && otherFiles.every((f) => mine.has(f))) { stackedOn = other.number; break; }
  }
  add("stacking", stackedOn ? "pending" : "pass",
    stackedOn ? `مكدّس فوق #${stackedOn} (ملفاته كلها ضمن هذا الـPR)` : "لا تكديس فوق PR مفتوح آخر");

  // 6) contracts/ يلزمها تعليق يبدأ بـ«موافقة المنسّق».
  const touchesContracts = fileNames.some((f) => f.startsWith("contracts/"));
  if (!touchesContracts) add("contracts", "pass", "لا ملفات contracts/");
  else {
    const ok = comments.some((c) => c.body.trimStart().startsWith("موافقة المنسّق"));
    add("contracts", ok ? "pass" : "fail", ok ? "موافقة المنسّق موجودة" : "يمس contracts/ ولا تعليق «موافقة المنسّق»");
  }

  // 7) العنوان [<الدور>] والفرع agent/<الدور>/… بنفس الدور، ولا أسماء نماذج.
  const titleRole = pr.title.match(/^\[(.+?)\]\s*\S/)?.[1] ?? "";
  const namingOk = Boolean(titleRole) && Boolean(role) && titleRole === role;
  const titleClean = pr.title.replace(/^\[.+?\]/, "");
  const branchClean = pr.head.ref.replace(/^agent\/[^/]+\//, "");
  const modelHits = [
    ["العنوان", modelNameHit(titleClean)],
    ["المتن", modelNameHit(pr.body)],
    ...commits.map((c) => [`التزام ${c.sha.slice(0, 7)}`, modelNameHit(c.commit?.message)]),
  ].filter(([, hit]) => hit);
  add("naming", namingOk && modelHits.length === 0 ? "pass" : "fail",
    modelHits.length ? `أسماء نماذج: ${modelHits.map(([w, h]) => `${h} في ${w}`).join("، ")}`
      : namingOk ? `الدور ${role} متطابق في العنوان والفرع` : `العنوان «${pr.title}» أو الفرع «${pr.head.ref}» بلا دور متطابق`);

  const ready = checks.every((c) => c.status === "pass");
  return { pr: prNumber, ready, checks };
}

const STATUS_AR = { pass: "ناجح", fail: "فاشل", pending: "معلّق" };

/** تقرير نصي عربي: سطر خلاصة ثم جدول الشرط والحالة والدليل. */
export function formatReport(result) {
  const lines = [`PR #${result.pr}: ${result.ready ? "جاهز للدمج" : "غير جاهز"}`];
  lines.push("الشرط | الحالة | الدليل");
  for (const c of result.checks) lines.push(`${c.id} | ${STATUS_AR[c.status]} | ${c.evidence}`);
  return lines.join("\n");
}

/** جلب حقيقي من GitHub API؛ الرمز اختياري. */
function ghFetcher(repo, token) {
  const headers = {
    Accept: "application/vnd.github+json",
    "X-GitHub-Api-Version": "2022-11-28",
    "User-Agent": "pr-gate",
  };
  if (token) headers.Authorization = `Bearer ${token}`;
  return async (path) => {
    const res = await fetch(`https://api.github.com/repos/${repo}/${path}`, { headers });
    if (!res.ok) throw new Error(`GitHub API: ${res.status} على ${path}`);
    return res.json();
  };
}

/** نقطة الدخول: تفسير الوسائط ورموز الخروج. deps.fetcher للاختبارات. */
export async function run(argv = process.argv.slice(2), env = process.env, deps = {}) {
  const prNumber = Number(argv.find((a) => /^\d+$/.test(a)));
  if (!prNumber) {
    console.error("الاستعمال: node tools/pr-gate.mjs <رقم-PR> [--json] [--repo owner/name]");
    return { code: 2 };
  }
  const repoIdx = argv.indexOf("--repo");
  const repo = repoIdx >= 0 ? argv[repoIdx + 1] : env.PR_GATE_REPO;
  if (!repo || !/^[\w.-]+\/[\w.-]+$/.test(repo)) {
    console.error("حدّد المستودع بـ--repo owner/name أو PR_GATE_REPO");
    return { code: 2 };
  }
  const fetcher = deps.fetcher ?? ghFetcher(repo, env.GITHUB_TOKEN);
  try {
    const result = await gate(prNumber, { fetcher });
    console.log(argv.includes("--json") ? JSON.stringify(result, null, 1) : formatReport(result));
    return { code: result.ready ? 0 : 1, result };
  } catch (error) {
    console.error(`تعذر فحص الجاهزية: ${error.message}`);
    return { code: 2 };
  }
}

if (process.argv[1] && process.argv[1].endsWith("pr-gate.mjs")) {
  const { code } = await run();
  process.exit(code);
}
